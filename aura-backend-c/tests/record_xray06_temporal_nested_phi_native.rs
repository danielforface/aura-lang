const XR06_SOURCE: &str = r###"
cell xray06_cpu_streak_next(previous: u32, cpu_milli: u32, comparable: u32, adjacent: u32):
    val mut next: u32 = 0
    if comparable == 1:
        if cpu_milli >= 700:
            if adjacent == 1:
                if previous < 4096:
                    next = previous + 1
                else:
                    next = 4096
            else:
                next = 1
    yield next

# Equivalent independent state machine for consecutive I/O transfer surges.
cell xray06_io_streak_next(previous: u32, read_kib_s: u32, write_kib_s: u32, comparable: u32, adjacent: u32):
    val mut next: u32 = 0
    if comparable == 1:
        if read_kib_s >= 16384:
            if adjacent == 1:
                if previous < 4096:
                    next = previous + 1
                else:
                    next = 4096
            else:
                next = 1
        else:
            if write_kib_s >= 16384:
                if adjacent == 1:
                    if previous < 4096:
                        next = previous + 1
                    else:
                        next = 4096
                else:
                    next = 1
    yield next

# Outstanding working-set debt is the required half-burst contraction,
# adjusted for later positive and negative changes. The adapter MUST prove
# previous+growth <= UINT32_MAX and that all magnitudes are valid u32.
cell xray06_memory_remaining(previous: u32, growth: u32, reduction: u32):
    val mut remaining: u32 = previous + growth
    if reduction >= remaining:
        remaining = 0
    else:
        remaining = remaining - reduction
    yield remaining

# States: 1 pending, 2 observed >=half retraction, 3 bounded window elapsed,
# 4 continuity lost or counter uncertain. No false "recovered" at missing data.
cell xray06_memory_phase(previous: u32, remaining: u32, age: u32, evidence_ok: u32):
    val mut phase: u32 = previous
    if previous == 1:
        if evidence_ok == 0:
            phase = 4
        else:
            if remaining == 0:
                phase = 2
            else:
                if age >= 3:
                    phase = 3
    yield phase

# Count synchronous measured dimensions: CPU-hot, I/O transfer surge,
# memory burst. Two or three co-occurring dimensions form a *coincidence* case,
# not evidence that one caused another.
cell xray06_signal_dimensions(cpu_milli: u32, read_kib_s: u32, write_kib_s: u32, growth_kib: u32):
    val mut dimensions: u32 = 0
    if cpu_milli >= 700:
        dimensions = dimensions + 1
    if read_kib_s >= 16384:
        dimensions = dimensions + 1
    else:
        if write_kib_s >= 16384:
            dimensions = dimensions + 1
    if growth_kib >= 32768:
        dimensions = dimensions + 1
    yield dimensions

# The provenance grade is generated by Aura from explicit evidence validity.
# 0=unknown, 1=complete sampled vector, 2=exactly source-rechecked,
# 3=exact-source and uninterrupted across the episode.
cell xray06_evidence_grade(comparable: u32, raw_verified: u32, contiguous: u32):
    val mut grade: u32 = 0
    if comparable == 1:
        grade = 1
        if raw_verified == 1:
            grade = 2
            if contiguous == 1:
                grade = 3
    yield grade
"###;

struct Scratch(PathBuf);
impl Scratch {
    fn new() -> Self {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let ns = SystemTime::now().duration_since(UNIX_EPOCH).unwrap().as_nanos();
        let id = NEXT.fetch_add(1, Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!(
            "aura-xray06-nested-phi-{}-{ns}-{id}", std::process::id()
        ));
        fs::create_dir_all(&dir).expect("create unique temporary native directory");
        Self(dir)
    }
}
impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

