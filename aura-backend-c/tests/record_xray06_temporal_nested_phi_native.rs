#[test]
fn xr06_nested_mutable_phi_produces_declared_native_ssa_and_correct_results() {
    let ast = aura_parse::parse_source(XR06_SOURCE).expect("real XR-06 source parses");
    Checker::new().check_program(&ast).expect("real XR-06 source type checks");
    let ir = lower_program(&ast).expect("real XR-06 nested mut source lowers");
    validate_module(&ir).expect("source nested Phi SSA validates");

    let phi_count = ir.functions.values()
        .flat_map(|f| f.blocks.iter())
        .flat_map(|b| b.insts.iter())
        .filter(|inst| matches!(&inst.kind, InstKind::Phi { .. }))
        .count();
    assert!(phi_count >= 6, "XR-06 source must actually cover nested mutable Phi: {phi_count}");

    // The Oracle is independent of the native C code generator. Both
    // original and optimized source-derived SSA must agree with these
    // product-level expected temporal state transitions.
    let vectors: &[(&str, &[u32], u32)] = &[
        ("xray06_cpu_streak_next", &[5, 700, 1, 1], 6),
        ("xray06_cpu_streak_next", &[4096, 701, 1, 1], 4096),
        ("xray06_cpu_streak_next", &[5, 699, 1, 1], 0),
        ("xray06_io_streak_next", &[5, 16384, 0, 1, 1], 6),
        ("xray06_io_streak_next", &[5, 0, 16384, 1, 1], 6),
        ("xray06_io_streak_next", &[5, 0, 0, 1, 1], 0),
        ("xray06_memory_remaining", &[50, 20, 80], 0),
        ("xray06_memory_remaining", &[50, 20, 15], 55),
        ("xray06_memory_phase", &[1, 0, 0, 1], 2),
        ("xray06_memory_phase", &[1, 7, 3, 1], 3),
        ("xray06_memory_phase", &[1, 7, 2, 1], 1),
        ("xray06_memory_phase", &[1, 7, 1, 0], 4),
        ("xray06_signal_dimensions", &[700, 16384, 0, 32768], 3),
        ("xray06_signal_dimensions", &[0, 0, 16384, 0], 1),
        ("xray06_signal_dimensions", &[0, 0, 0, 0], 0),
        ("xray06_evidence_grade", &[1, 1, 1], 3),
        ("xray06_evidence_grade", &[1, 1, 0], 2),
        ("xray06_evidence_grade", &[0, 1, 1], 0),
    ];
    let mut optimized = ir.clone();
    optimize_module(&mut optimized);
    validate_module(&optimized).expect("optimized XR-06 source SSA validates");

    for (label, module) in [("original", &ir), ("optimized", &optimized)] {
        for (name, args, expected) in vectors {
            let input = args.iter().copied().map(OracleValue::U32).collect::<Vec<_>>();
            let result = run_oracle_entry(module, name, &input, OracleConfig::default())
                .unwrap_or_else(|err| panic!("{label}: Oracle '{name}' error: {err}"));
            assert_eq!(result.return_value, Some(OracleValue::U32(*expected)),
                "{label}: '{name}' for {args:?}");
        }
        let c = emit_module_with_source_contract(&ast, module, None)
            .unwrap_or_else(|err| panic!("{label}: exact Aura source must generate C: {err}"));
        let dir = Scratch::new();
        fs::write(dir.0.join("aura_runtime.h"), &c.runtime_h).unwrap();
        fs::write(dir.0.join("module.c"), &c.module_c).unwrap();
        fs::write(dir.0.join("driver.c"), DRIVER).unwrap();
        for opt in ["-O0", "-O2"] {
            let exe = dir.0.join(format!("xr06_{}_{}", label, &opt[1..]));
            let cc = Command::new("clang")
                .args(["-std=gnu11", "-Wall", "-Werror", "-fsanitize=undefined",
                    "-fno-sanitize-recover=all", opt, "-I"])
                .arg(&dir.0)
                .arg(dir.0.join("module.c"))
                .arg(dir.0.join("driver.c"))
                .arg("-o").arg(&exe)
                .output().expect("Clang available in the Q03 native gate");
            assert!(cc.status.success(),
                "{label}/{opt}: XR-06 compiler or undeclared Phi: {}\n{}",
                String::from_utf8_lossy(&cc.stderr), c.module_c);
            let run = Command::new(exe).output().expect("run XR-06 native process");
            assert!(run.status.success(),
                "{label}/{opt}: incorrect XR-06 temporal states, exit {:?}: {}",
                run.status.code(), String::from_utf8_lossy(&run.stderr));
        }
    }
}

#[test]
fn xr06_corrupt_nested_phi_predecessor_is_rejected_not_emitted() {
    let ast = aura_parse::parse_source(XR06_SOURCE).unwrap();
    let mut ir = lower_program(&ast).expect("source lowering");
    let mut changed = false;
    for func in ir.functions.values_mut() {
        for block in &mut func.blocks {
            for inst in &mut block.insts {
                if let InstKind::Phi { incomings } = &mut inst.kind {
                    if incomings.len() >= 2 {
                        incomings.pop();
                        changed = true;
                        break;
                    }
                }
            }
            if changed { break; }
        }
        if changed { break; }
    }
    assert!(changed, "source regression must contain a multi-predecessor Phi");
    let err = validate_module(&ir).err()
        .expect("missing incoming CFG edge must fail SSA validation");
    assert!(err.message.contains("missing incoming predecessor"),
        "expected precise fail-closed Phi diagnostic: {err}");
}
