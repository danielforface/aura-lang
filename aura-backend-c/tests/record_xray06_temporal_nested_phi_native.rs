//! Q03-001 real downstream regression: XR-06 temporal state machine from
//! product commit 0a8983db3a5879d776e2cb7a323635b15003263d.
//! The historical Windows C compile failed with undeclared Phi values (v84,
//! v86, v106). Prove current Core source->IR->native C on both original and
//! optimized SSA. This is NOT Win64 or integrated A+B qualification.

